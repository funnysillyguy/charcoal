// Generates src/components/icons.jsx from Phosphor's definitions: regular weight for every icon,
// plus the fill weight for the few drawn solid. No runtime dependency on the icon package.
// To add an icon: add `export const Name = make('PhosphorName', 'Name');` to icons.jsx, then
//   npm i --no-save @phosphor-icons/react@2.1.10 && node scripts/gen_icons.mjs
import fs from 'node:fs';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
const root = '/home/claude/charcoal';
const shim = fs.readFileSync(`${root}/src/components/icons.jsx`, 'utf8');
const pairs = [...shim.matchAll(/^export const (\w+) = (?:wrap\(P(\w+)|make\('(\w+)'), '\w+'\);$/gm)].map((m) => [m[1], m[2] || m[3]]);
const FILL = new Set(['Play', 'PaperPlaneRight', 'Square', 'Heart']);
const defs = {};
for (const [, ph] of pairs) {
  if (defs[ph]) continue;
  const mod = await import(`${root}/node_modules/@phosphor-icons/react/dist/defs/${ph}.es.js`);
  const map = mod.default;
  const r = renderToStaticMarkup(map.get('regular'));
  const f = FILL.has(ph) ? renderToStaticMarkup(map.get('fill')) : null;
  defs[ph] = f ? { r, f } : { r };
}
const lines = [];
lines.push("// Charcoal's icon set: Phosphor (MIT, phosphoricons.com) path data, generated by");
lines.push('// scripts/gen_icons.mjs. Same props as before (size, className, fill, aria-*), so call sites stay unchanged.');
lines.push("import { forwardRef } from 'react';");
lines.push('');
lines.push('/* eslint-disable */');
lines.push('const D = ' + JSON.stringify(defs) + ';');
lines.push('');
lines.push('function make(key, name) {');
lines.push('  const C = forwardRef(function Icon({ size = 24, fill, strokeWidth, absoluteStrokeWidth, weight, className, style, ...rest }, ref) {');
lines.push('    void strokeWidth;');
lines.push('    void absoluteStrokeWidth;');
lines.push('    const d = D[key];');
lines.push("    const solid = (weight === 'fill' || (fill && fill !== 'none')) && d.f;");
lines.push('    return (');
lines.push('      <svg');
lines.push('        ref={ref}');
lines.push('        xmlns="http://www.w3.org/2000/svg"');
lines.push('        width={size}');
lines.push('        height={size}');
lines.push('        viewBox="0 0 256 256"');
lines.push('        fill="currentColor"');
lines.push("        className={className ? `icon ${className}` : 'icon'}");
lines.push('        style={style}');
lines.push("        aria-hidden={rest['aria-label'] ? undefined : true}");
lines.push('        {...rest}');
lines.push('        dangerouslySetInnerHTML={{ __html: solid ? d.f : d.r }}');
lines.push('      />');
lines.push('    );');
lines.push('  });');
lines.push('  C.displayName = name;');
lines.push('  return C;');
lines.push('}');
lines.push('');
for (const [name, ph] of pairs) lines.push(`export const ${name} = make('${ph}', '${name}');`);
fs.writeFileSync(`${root}/src/components/icons.jsx`, lines.join('\n') + '\n');
console.log(pairs.length, 'exports,', Object.keys(defs).length, 'shapes');
